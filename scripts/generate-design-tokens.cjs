// Source of truth: src/design/tokens.json. Re-run after changing the palette.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const tokens = require('../src/design/tokens.json');
const entries = (obj, prefix = '') => Object.entries(obj).map(([key, value]) => `  --${prefix}${key}: ${value};`).join('\n');
const aliases = {
  'foreground':'text-primary', 'gc-screen-bg':'background', 'gc-menu-bg':'navigation', 'gc-menu-text':'on-navigation', 'gc-menu-icon':'primary', 'gc-menu-hover':'navigation-hover',
  'gc-menu-active-bg':'selection', 'gc-menu-active-text':'selection-text', 'gc-text-light':'text-primary', 'gc-text-dark':'surface',
  'gc-button-dark-bg':'primary', 'gc-button-dark-text':'on-primary', 'gc-button-light-bg':'surface', 'gc-button-light-text':'text-primary',
  'gc-btn-dark-bg':'primary', 'gc-btn-dark-text':'on-primary', 'gc-modal-bg':'surface', 'gc-modal-text':'text-primary', 'gc-modal-btn-bg':'primary', 'gc-modal-btn-text':'on-primary',
  'gc-success':'success', 'gc-error':'danger', 'gc-warning':'warning'
};
let css = `/* Generated by scripts/generate-design-tokens.cjs; edit tokens.json. */\n:root {\n${entries(tokens.brand, 'gc-')}\n${entries(tokens.light)}\n  color-scheme: light;\n${Object.entries(aliases).map(([k,v]) => `  --${k}: var(--${v});`).join('\n')}\n}\n:root[data-theme="dark"] {\n${entries(tokens.dark)}\n  color-scheme: dark;\n}\n`;
css += `@theme inline {\n${Object.keys(tokens.light).map(k => `  --color-${k}: var(--${k});`).join('\n')}\n  --font-sans: var(--font-inter), Arial, sans-serif;\n}\n`;
css += `@media print {\n  :root, :root[data-theme="dark"] {\n${entries(tokens.light)}\n    color-scheme: light;\n  }\n}\n`;
fs.writeFileSync(path.join(root, 'src/design/tokens.css'), css);
