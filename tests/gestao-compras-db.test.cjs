const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const { randomUUID } = require('node:crypto');
const { PGlite } = require('@electric-sql/pglite');
test('compras: registro, idempotência, recebimento parcial, estorno, cancelamento e isolamento', async () => {
 const db = new PGlite();
 try {
 const empresa=randomUUID(), outra=randomUUID(), pedido=randomUUID();
 await db.exec(`create role anon; create role authenticated; create schema auth; create schema glasscode_private;
 create function auth.uid() returns uuid language sql stable as $$select '10000000-0000-0000-0000-000000000001'::uuid$$;
 create table public.empresas(id uuid primary key);
 create table public.gc_pedidos(id uuid primary key, empresa_id uuid, versao integer, situacao text);
 create function public.gc_modulo_permitido(e uuid,m text) returns boolean language sql stable as $$select e=current_setting('test.empresa')::uuid and current_setting('test.acesso')='sim'$$;
 create function glasscode_private.pedido_empresa() returns uuid language plpgsql as $$begin if current_setting('test.acesso')<>'sim' then raise exception 'Sem acesso'; end if;return current_setting('test.empresa')::uuid;end$$;
 insert into public.empresas values('${empresa}'),('${outra}');insert into public.gc_pedidos values('${pedido}','${empresa}',1,'conferencia');
 set test.empresa='${empresa}'; set test.acesso='sim';`);
 await db.exec(fs.readFileSync('database/20261108_gestao_compras.sql','utf8'));
 await db.exec(fs.readFileSync('database/20261109_fornecedores_compras.sql','utf8'));
 await db.exec(fs.readFileSync('database/20261110_fornecedores_dados_cadastrais.sql','utf8'));
 await db.exec('set role authenticated');
 const material={descricao:'Ferragem fictícia',unidade:'und',medida:'',cor:'Preto'};
 const linhas=[{pedido_id:pedido,versao:1,chave:pedido+':manual:0',material,necessario:10,quantidade:6,preco:20}];
 const token=randomUUID();
 const registrar=(l=linhas,t=randomUUID())=>db.query('select public.gc_registrar_compra($1,$2,$3,$4,$5,$6) as id',[t,'Fornecedor fictício','TESTE',null,'',JSON.stringify(l)]);
 const compra=(await registrar(linhas,token)).rows[0].id;
 assert.equal((await registrar(linhas,token)).rows[0].id,compra);
 assert.equal((await db.query('select count(*)::int as n from public.gc_compras')).rows[0].n,1);
 await assert.rejects(registrar(),/já comprada|superior/);
 await assert.rejects(registrar([{...linhas[0],versao:0,quantidade:1}]),/alterado/);
 await assert.rejects(registrar([{...linhas[0],pedido_id:randomUUID()}]),/indisponível/);
 const item=(await db.query('select id from public.gc_compra_itens')).rows[0].id;
 const receber=(q,t=randomUUID())=>db.query('select public.gc_receber_compra($1,$2,$3,$4)',[item,q,'Entrega fictícia',t]);
 const rtoken=randomUUID(); await receber(3,rtoken); await receber(3,rtoken);
 assert.equal(Number((await db.query('select sum(quantidade) as n from public.gc_compra_eventos')).rows[0].n),3);
 await assert.rejects(receber(4),/superior/);
 await assert.rejects(receber(-1),/inválida/);
 await assert.rejects(db.query('select public.gc_cancelar_compra($1,$2,$3)',[compra,'Cancelamento fictício',randomUUID()]),/Estorne/);
 await db.exec(`set test.empresa='${outra}'`);
 assert.equal((await db.query('select * from public.gc_compras')).rows.length,0);
 assert.equal((await db.query('select * from public.gc_compra_itens')).rows.length,0);
 assert.equal((await db.query('select * from public.gc_compra_eventos')).rows.length,0);
 await assert.rejects(receber(1),/indisponível/);
 await db.exec(`set test.empresa='${empresa}'`);
 const ev=(await db.query("select id from public.gc_compra_eventos where tipo='recebimento'")).rows[0].id;
 await db.query('select public.gc_estornar_recebimento($1,$2,$3)',[ev,'Recebimento incorreto',randomUUID()]);
 await assert.rejects(db.query('select public.gc_estornar_recebimento($1,$2,$3)',[ev,'Duplicado',randomUUID()]),/já estornado/);
 await db.query('select public.gc_cancelar_compra($1,$2,$3)',[compra,'Cancelamento fictício',randomUUID()]);
 await assert.rejects(receber(1),/cancelada/);
 await registrar(); // Cancelamento devolve a necessidade de compra.
 await assert.rejects(db.exec('delete from public.gc_compras'),/permission denied/);
 await assert.rejects(db.exec('truncate public.gc_compras cascade'),/permission denied/);
 const fornecedor=randomUUID();
 await db.query('insert into public.gc_fornecedores(id,empresa_id,nome) values($1,$2,$3)',[fornecedor,empresa,'Fornecedor teste']);
 await db.query('update public.gc_fornecedores set dados_cadastrais=$1 where id=$2',[JSON.stringify({tipo_pessoa:'juridica',cidade:'Cidade teste',logradouro:'Rua teste'}),fornecedor]);
 assert.equal((await db.query('select dados_cadastrais from public.gc_fornecedores where id=$1',[fornecedor])).rows[0].dados_cadastrais.cidade,'Cidade teste');
 const linhaFornecedor=[{...linhas[0],quantidade:1,chave:pedido+':manual:1'}];
 const nova=(await db.query('select public.gc_registrar_compra_fornecedor($1,$2,$3,$4,$5,$6) as id',[randomUUID(),fornecedor,'',null,'',JSON.stringify(linhaFornecedor)])).rows[0].id;
 assert.equal((await db.query('select fornecedor_id from public.gc_compras where id=$1',[nova])).rows[0].fornecedor_id,fornecedor);
 await db.exec(`set test.empresa='${outra}'`);
 assert.equal((await db.query('select * from public.gc_fornecedores')).rows.length,0);
 await assert.rejects(db.query('select public.gc_registrar_compra_fornecedor($1,$2,$3,$4,$5,$6)',[randomUUID(),fornecedor,'',null,'',JSON.stringify(linhaFornecedor)]),/fornecedor ativo/);
 await db.exec(`set test.empresa='${empresa}'`);
 await db.query('update public.gc_fornecedores set ativo=false where id=$1',[fornecedor]);
 await assert.rejects(db.query('select public.gc_registrar_compra_fornecedor($1,$2,$3,$4,$5,$6)',[randomUUID(),fornecedor,'',null,'',JSON.stringify(linhaFornecedor)]),/fornecedor ativo/);
 await db.exec("set test.acesso='nao'");
 await assert.rejects(registrar(),/Sem acesso/);
 assert.equal((await db.query('select * from public.gc_compras')).rows.length,0);
 await db.exec('set role anon');
 await assert.rejects(registrar(),/permission denied/);
 } finally { await db.close(); }
});
